from django.contrib import admin
from django.contrib.auth.admin import UserAdmin as BaseUserAdmin
from django.contrib.auth.forms import (
    UserChangeForm as BaseUserChangeForm,
    UserCreationForm as BaseUserCreationForm,
)
from django.utils import timezone

from .models import DuplicateRegistrationFlag, User, UserLevel


class CustomUserCreationForm(BaseUserCreationForm):
    """Form for creating users with our custom user model."""

    class Meta(BaseUserCreationForm.Meta):
        model = User
        fields = (
            "email",
            "full_name",
            "platform_username",
            "whatsapp_number",
            "state",
            "gender",
        )

    def clean_email(self):
        # Match UserManager.create_user: emails are stored lower-cased and
        # login looks them up that way.
        return self.cleaned_data["email"].strip().lower()


class CustomUserChangeForm(BaseUserChangeForm):
    """Form for editing existing users."""

    class Meta(BaseUserChangeForm.Meta):
        model = User
        fields = "__all__"


@admin.register(User)
class CustomUserAdmin(BaseUserAdmin):
    actions = [
        "approve_selected_users",
        "disable_selected_users",
    ]
    form = CustomUserChangeForm
    add_form = CustomUserCreationForm

    ordering = ("email",)

    list_display = (
        "email",
        "full_name",
        "platform_username",
        "referral_code",
        "gender",
        "approval_status",
        "is_active",
        "is_staff",
    )

    list_filter = (
        "approval_status",
        "gender",
        "is_active",
        "is_staff",
    )

    search_fields = (
        "email",
        "full_name",
        "platform_username",
        "whatsapp_number",
        "referral_code",
    )

    fieldsets = (
        ("Login", {
            "fields": ("email", "password"),
        }),
        ("Personal Information", {
            "fields": (
                "full_name",
                "platform_username",
                "whatsapp_number",
                "state",
                "gender",
            ),
        }),
        ("Account Status", {
            "fields": ("approval_status", "is_active", "referral_code"),
        }),
        ("Permissions", {
            "fields": (
                "is_staff",
                "is_superuser",
                "groups",
                "user_permissions",
            ),
        }),
        ("Important Dates", {
            "fields": ("last_login", "date_joined"),
        }),
    )

    add_fieldsets = (
        (None, {
            "classes": ("wide",),
            "fields": (
                "email",
                "full_name",
                "platform_username",
                "whatsapp_number",
                "state",
                "gender",
                "password1",
                "password2",
            ),
        }),
    )

    # The referral code is generated by User.save() and never edited.
    readonly_fields = ("last_login", "date_joined", "referral_code")

    filter_horizontal = ("groups", "user_permissions")

    def _set_status(self, request, queryset, new_status):
        """Bulk status change with the same audit fields as the admin API."""
        users = queryset.filter(
            is_staff=False,
            is_superuser=False,
        ).exclude(approval_status=new_status)

        return users.update(
            approval_status=new_status,
            is_active=new_status != User.ApprovalStatus.DISABLED,
            status_reason=f"{User.ApprovalStatus(new_status).label} by an administrator.",
            status_change_source=User.StatusChangeSource.ADMIN,
            status_changed_by=request.user,
            status_changed_at=timezone.now(),
        )

    @admin.action(description="Approve selected user accounts")
    def approve_selected_users(self, request, queryset):
        count = self._set_status(request, queryset, User.ApprovalStatus.APPROVED)

        self.message_user(
            request,
            f"{count} user account(s) approved successfully.",
        )

    @admin.action(description="Disable selected user accounts")
    def disable_selected_users(self, request, queryset):
        count = self._set_status(request, queryset, User.ApprovalStatus.DISABLED)

        self.message_user(
            request,
            f"{count} user account(s) disabled successfully.",
        )


@admin.register(DuplicateRegistrationFlag)
class DuplicateRegistrationFlagAdmin(admin.ModelAdmin):
    list_display = (
        "id",
        "new_user",
        "matched_user",
        "match_type",
        "status",
        "created_at",
        "reviewed_at",
    )

    list_filter = (
        "status",
        "match_type",
        "created_at",
    )

    search_fields = (
        "new_user__email",
        "matched_user__email",
        "new_user__platform_username",
        "matched_user__platform_username",
        "new_user__whatsapp_number",
        "matched_user__whatsapp_number",
    )

    readonly_fields = (
        "new_user",
        "matched_user",
        "match_type",
        "created_at",
        "reviewed_by",
        "reviewed_at",
    )

    fields = (
        "new_user",
        "matched_user",
        "match_type",
        "status",
        "admin_notes",
        "created_at",
        "reviewed_by",
        "reviewed_at",
    )

    def save_model(self, request, obj, form, change):
        if obj.status != DuplicateRegistrationFlag.ReviewStatus.PENDING:
            obj.reviewed_by = request.user
            obj.reviewed_at = timezone.now()
        else:
            obj.reviewed_by = None
            obj.reviewed_at = None

        super().save_model(request, obj, form, change)

    def has_add_permission(self, request):
        return False

    def has_delete_permission(self, request, obj=None):
        return False


